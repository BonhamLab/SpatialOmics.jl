# # IO / File handling
#
# ## Folder Structure
#
# The folder structure is as follows:
#
# ```
# ./
# ├── experiment_name
# │   ├── experiment_name_properties.toml
# │   ├── slides/
# │   │   ├── slide1/
# │   │   │   ├── slide1_properties.toml
# │   │   │   ├── fovs/
# │   │   │   │   ├── fov1.toml
# │   │   │   │   ├── fov2.toml
# │   │   │   │   ├── ...
# │   │   │   ├── rois/
# │   │   │   │   ├── roi1.toml
# │   │   │   │   ├── roi2.toml
# │   │   │   │   ├── ...
# │   │   │   ├── imgs/
# │   │   │   │   ├── fov1.tif
# │   │   │   │   ├── fov2.tif
# │   │   │   │   ├── ...
# │   │   ├── slide2
# │   │   │   ├── etc...
# ```

